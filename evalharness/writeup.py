"""Generated results block of the README (Step 16).

The README is written by hand EXCEPT one block between two markers. That block
is built here from the reports already stored in `run_reports` (Steps 10, 11 and
12) and the calibration status (Step 9), so no number in it is typed by hand.
`check` regenerates the block and fails when the README no longer matches the
database.

No LLM call, no re-run, nothing written to the database: only the README file
is written, and only between the markers.

CLI (python -m evalharness.writeup ...):
    render              print the block; write nothing
    update [--readme P] replace the block in the README
    check  [--readme P] 0 = README block matches the database, 1 = it differs,
                        2 = refused (no database, no stored report, bad markers)
"""

import argparse
import sys
from contextlib import closing

from evalharness import store
from evalharness.experiments import _delta
from evalharness.report import _calibration_status, _fmt_calibration, _fmt_rate_pct
from evalharness.runner import DEFAULT_HARNESS_CONFIG, load_harness_config
from evalharness.testset import resolve_path

START_MARKER = "<!-- results:start (generated by python -m evalharness.writeup; do not edit by hand) -->"
END_MARKER = "<!-- results:end -->"
WRITEUP_KEYS = {"readme_path"}


class WriteupRefused(Exception):
    """A required stored report is missing, or the README has no (or duplicate) markers."""


# ---------------------------------------------------------------- config

def load_writeup_config(harness: dict) -> dict:
    """The checked `writeup` block of configs/harness.yaml; ValueError names the problem."""
    cfg = harness.get("writeup")
    if not isinstance(cfg, dict):
        raise ValueError("harness config: 'writeup' must be a mapping")
    missing, extra = WRITEUP_KEYS - set(cfg), set(cfg) - WRITEUP_KEYS
    if missing or extra:
        raise ValueError(f"harness config: writeup keys missing {sorted(missing)}, "
                         f"unknown {sorted(extra)}")
    if not isinstance(cfg["readme_path"], str) or not cfg["readme_path"].strip():
        raise ValueError("harness config: 'writeup.readme_path' must be a non-empty string")
    return cfg


# ---------------------------------------------------------------- read the stored reports

def _latest_per_run(rows: list[dict]) -> list[dict]:
    """One report per run (the newest stored), in the order of their first appearance."""
    newest = {}
    for row in rows:
        newest[row["run_id"]] = row
    return list(newest.values())


def build_results(conn, harness: dict) -> dict:
    """Everything the README block needs, read from run_reports and calibration_reports.

    baseline    the stored Step 10 report of the v0 dev run
    experiments the stored Step 11 rows whose config is NOT the baseline config, in run order
    twin        Step 11 rows of the baseline config itself (an identical rerun, not an experiment)
    heldout     the stored Step 12 confirmation report
    regression  the stored Step 13 checks (gate verdict and flag rate per pair of runs)
    calibration live Step 9 status of each judge, on the baseline run
    Raises WriteupRefused when the baseline, the experiments or the held-out report is missing.
    """
    baselines = store.list_run_reports(conn, "baseline")
    if not baselines:
        raise WriteupRefused("no stored baseline report (python -m evalharness.report)")
    baseline = baselines[-1]["report"]
    base_run_id = baseline["metadata"]["run_id"]
    base_config = baseline["metadata"]["config_path"]

    rows = _latest_per_run([r["report"] for r in store.list_run_reports(conn, "experiment")])
    for row in rows:
        if row["baseline_run_id"] != base_run_id:
            raise WriteupRefused(f"experiment run {row['run_id']} was compared with "
                                 f"{row['baseline_run_id']}, not the baseline {base_run_id}")
    experiments = [r for r in rows if r["config_path"] != base_config]
    twin = [r for r in rows if r["config_path"] == base_config]
    if not experiments:
        raise WriteupRefused("no stored experiment reports (python -m evalharness.experiments compare)")

    heldout_reports = store.list_run_reports(conn, "heldout")
    if not heldout_reports:
        raise WriteupRefused("no stored held-out report (python -m evalharness.heldout confirm)")
    heldout = heldout_reports[-1]["report"]

    # Step 13 regression checks: one row per (run, reference run, flag version) as stored.
    regression = {}
    for row in store.list_run_reports(conn, "regression"):
        report = row["report"]
        regression[(report["run_id"], report["against_run_id"], report["flag_version"])] = report

    versions = baseline["metadata"]["versions"]
    calibration = {judge: _calibration_status(conn, base_run_id, judge, versions[judge])
                   for judge in ("faithfulness", "relevance")}
    return {"baseline": baseline, "experiments": experiments, "twin": twin, "heldout": heldout,
            "regression": list(regression.values()), "calibration": calibration, "accepted": (store.get_accepted_runs(conn, "dev") or [None])[0]}


# ---------------------------------------------------------------- the block

def _rate(summary: dict) -> str:
    """'8.75% [4.30%, 16.98%] (7/80)', or 'n = 0' (never 0%) when nothing was judged."""
    return "n = 0" if summary["n"] == 0 else _fmt_rate_pct(summary)


def _p(value: float | None) -> str:
    return "-" if value is None else f"{value:.4f}"


def format_results_markdown(results: dict) -> str:
    """The block body: headline table, experiment table, calibration status. Plain markdown."""
    base, held = results["baseline"], results["heldout"]
    label = base["judge_label"]["faithfulness"]
    pct = round(base["confidence"] * 100)
    chosen_config = held["registration"]["chosen_config"]
    chosen = next((r for r in results["experiments"] if r["config_path"] == chosen_config), None)
    if chosen is None:
        raise WriteupRefused(f"the held-out chosen config {chosen_config} has no stored experiment row")
    verdict = held["verdict"]

    lines = [
        f"Ungrounded-answer rate, {pct}% Wilson interval, k/n in brackets. Judge: **{label}** "
        "(see the calibration status below).",
        "",
        f"| Config | Dev ({base['ungrounded']['all']['n']} queries) "
        f"| Held-out ({held['runs']['baseline']['ungrounded']['all']['n']} unseen queries) |",
        "|---|---|---|",
        f"| `{base['metadata']['config_path']}` (baseline) | {_rate(base['ungrounded']['all'])} "
        f"| {_rate(held['runs']['baseline']['ungrounded']['all'])} |",
        f"| `{chosen_config}` (chosen) | {_rate(chosen['experiment']['ungrounded']['all'])} "
        f"| {_rate(held['runs']['chosen']['ungrounded']['all'])} |",
        "",
        f"- Dev, chosen vs baseline: improved {chosen['flips']['counts']['improved']}, regressed "
        f"{chosen['flips']['counts']['regressed']}, exact paired p = {_p(chosen['p_value'])}.",
        f"- Held-out, chosen vs baseline: improved {verdict['improved']}, regressed "
        f"{verdict['regressed']}, exact paired p = {_p(verdict['p_value'])}. Verdict: "
        f"`{verdict['label']}` ({verdict['wording']}).",
        f"- Baseline run `{base['metadata']['run_id']}`; held-out runs "
        f"`{held['run_ids']['baseline']}` and `{held['run_ids']['chosen']}`.",
    ]
    for row in results["twin"]:
        lines.append(f"- Identical rerun of the baseline config from the cache (run `{row['run_id']}`): "
                     f"{_rate(row['experiment']['ungrounded']['all'])}, improved "
                     f"{row['flips']['counts']['improved']}, regressed {row['flips']['counts']['regressed']}.")

    lines += ["", "### Experiments (dev, one variable each)", "",
              "| Variable | Run | Ungrounded | Change | Improved / regressed | Exact p | False refusals |",
              "|---|---|---|---|---|---|---|"]
    lines.append(f"| baseline (reference) | `{base['metadata']['run_id']}` "
                 f"| {_rate(base['ungrounded']['all'])} | - | - | - | {len(base['false_refusals'])} |")
    for row in results["experiments"]:
        c = row["flips"]["counts"]
        lines.append(f"| {row['variable'] or row['config_path']} | `{row['run_id']}` "
                     f"| {_rate(row['experiment']['ungrounded']['all'])} | {_delta(row)} "
                     f"| {c['improved']} / {c['regressed']} | {_p(row['p_value'])} "
                     f"| {len(row['experiment']['false_refusals'])} |")

    if results["regression"]:
        lines += ["", "### Regression checks stored (Step 13)", "",
                  "| Run | Compared with | Gate | Ungrounded change | Flag rate | Flag reasons |",
                  "|---|---|---|---|---|---|"]
        for rep in results["regression"]:
            g = rep["gate"]
            reasons = ", ".join(f"{k} {v}" for k, v in rep["flag_reason_counts"].items()) or "none"
            lines.append(f"| `{rep['run_id']}` | `{rep['against_run_id']}` | {g['verdict']} "
                         f"| {g['delta_points']:+.2f} pts | {_rate(rep['flag_rate'])} | {reasons} |")
        lines += ["", "The flag rate is review workload, not a quality number: it depends on which two "
                      "runs are compared (`answer_changed` flags grow with the difference between them)."]
    lines += ["", "### Judge calibration (Step 9)", "", "| Judge | Version | Status |", "|---|---|---|"]
    for judge in ("faithfulness", "relevance"):
        version = base["metadata"]["versions"][judge]
        lines.append(f"| {judge} | `{version}` | {_fmt_calibration(results['calibration'][judge])} |")
    return "\n".join(lines)


# ---------------------------------------------------------------- README block

def _locate(readme_text: str) -> tuple[int, int]:
    """(index just after the start marker, index of the end marker); WriteupRefused if not exactly one pair."""
    if readme_text.count(START_MARKER) != 1 or readme_text.count(END_MARKER) != 1:
        raise WriteupRefused("the README must contain the start marker and the end marker exactly once")
    start = readme_text.index(START_MARKER) + len(START_MARKER)
    end = readme_text.index(END_MARKER)
    if end < start:
        raise WriteupRefused("the end marker comes before the start marker")
    return start, end


def replace_block(readme_text: str, block_body: str) -> str:
    """readme_text with the text between the markers replaced; everything else is byte-identical."""
    start, end = _locate(readme_text)
    return readme_text[:start] + "\n" + block_body.strip("\n") + "\n" + readme_text[end:]


def check_readme(readme_text: str, block_body: str) -> list[str]:
    """[] when the README block equals block_body, else one line naming the first difference."""
    start, end = _locate(readme_text)
    have = readme_text[start:end].strip("\n").splitlines()
    want = block_body.strip("\n").splitlines()
    if have == want:
        return []
    for number, (a, b) in enumerate(zip(have, want), start=1):
        if a != b:
            return [f"block line {number} differs:\n  README: {a}\n  stored: {b}"]
    return [f"block has {len(have)} lines in the README but {len(want)} from the database"]


# ---------------------------------------------------------------- CLI

def _refuse(problem: str) -> int:
    print(f"error: {problem}", file=sys.stderr)
    return 2


def _build_body(harness: dict) -> tuple[str, dict]:
    """The generated block and its results; the database must already exist (connect would create one)."""
    db_path = resolve_path(harness["db_path"])
    if not db_path.exists():
        raise WriteupRefused(f"results database not found: {db_path} (a fresh clone has none; "
                             "the README block is generated on the author's machine)")
    with closing(store.connect(db_path)) as conn:
        results = build_results(conn, harness)
    return format_results_markdown(results), results


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m evalharness.writeup",
                                     description="Generate / check the results block of the README.")
    parser.add_argument("--harness-config", default=DEFAULT_HARNESS_CONFIG)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("render", help="print the generated block")
    for name, text in (("update", "replace the block in the README"),
                       ("check", "fail when the README block differs from the database")):
        command = sub.add_parser(name, help=text)
        command.add_argument("--readme", help="README path (default: writeup.readme_path)")
    args = parser.parse_args(argv)

    try:
        harness = load_harness_config(args.harness_config)
        cfg = load_writeup_config(harness)
        body, results = _build_body(harness)
        if args.command == "render":
            print(body)
            return 0
        readme_path = resolve_path(args.readme or cfg["readme_path"])
        text = readme_path.read_text(encoding="utf-8")
        if args.command == "update":
            new_text = replace_block(text, body)
            if new_text == text:
                print(f"{readme_path.name} results block unchanged")
            else:
                readme_path.write_text(new_text, encoding="utf-8")
                print(f"updated the results block in {readme_path}")
            return 0
        problems = check_readme(text, body)
    except (WriteupRefused, ValueError, OSError) as error:
        return _refuse(str(error))
    if problems:
        print("README results block differs from the database:\n" + "\n".join(problems))
        return 1
    print(f"README results block matches {harness['db_path']} (baseline run "
          f"{results['baseline']['metadata']['run_id']}, {len(results['experiments'])} experiments, "
          f"held-out runs {results['heldout']['run_ids']['baseline']} and "
          f"{results['heldout']['run_ids']['chosen']})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
